ROOT = Path(__file__).resolve().parents[2]
PHYSICS = ROOT / "harness/physics"
INPUT = ROOT / "harness/examples/dev006/input"
FIXTURES = ROOT / "tests/workbench/fixtures"
FINAL_LST = (FIXTURES / "dev006_bgmn/DEV006_rietveld.lst").read_text()
CONTROL_LST = (FIXTURES / "dev006_bgmn_control/DEV006_rietveld_texture_control.lst").read_text()
CONTROL_SAV = "DEV006_rietveld_texture_control.sav"
FINAL_SAV = "DEV006_rietveld.sav"
THREE = ("cod_1010093", "cod_9008283", "cod_1526458")
STAMP = re.compile(r" // generated by axa .*")


class FakeBGMN:
    """Writes each stage's LIST and DIAGRAMM and keeps what BGMN would have read."""

    def __init__(self, *, fail: Exception | None = None, final_lst: str = FINAL_LST, control_lst: str = CONTROL_LST) -> None:
        self.read: dict[str, dict[str, object]] = {}
        self.fail = fail
        self.final_lst = final_lst
        self.control_lst = control_lst

    def compute_timeout(self, *args, **kwargs) -> tuple[int, int]:
        return (1, 1)

    def run_with_monitor(self, sav: Path, **kwargs) -> Path:
        text = sav.read_text()
        structures = re.findall(r"^STRUC\[\d+\]=(\S+)", text, re.MULTILINE)
        self.read[sav.name] = {"sav": text, "str": [(sav.parent / name).read_text() for name in structures]}
        if sav.name == CONTROL_SAV:
            if self.fail is not None:
                raise self.fail
            lst = self.control_lst
        else:
            lst = self.final_lst if sav.name == FINAL_SAV else FINAL_LST
        names = re.findall(r"Local parameters and GOALs for phase (\S+)", lst)
        if len(structures) != len(names):
            lst = _keeping_phases(lst, len(structures))
        rwp = re.search(r"Rwp=([0-9.]+)", lst)[1]
        (sav.parent / f"{sav.stem}.lst").write_text(lst)
        (sav.parent / f"{sav.stem}.dia").write_text(f"TITEL={sav.stem} Rwp={rwp}\n 10.0 1.0 1.0 1.0\n 10.1 1.0 1.0 1.0\n")
        return sav.parent / f"{sav.stem}.lst"


def _keeping_phases(lst: str, count: int) -> str:
    head, *phases = re.split(r"(?=Local parameters and GOALs for phase)", lst)
    return head + "".join(phases[:count])


def _library() -> dict[str, dict]:
    manifest = json.loads((INPUT / "candidates/DEV006/manifest.json").read_text())
    return {row["candidate_id"]: row for row in manifest["candidates"]}


def _config(tmp_path: Path, **fields) -> RefinementConfig:
    return RefinementConfig(n_threads=1, working_dir=tmp_path, prefer_tmpfs=False, enable_ml_pawley_bypass=False, **fields)


def _refine(monkeypatch, tmp_path: Path, bgmn: FakeBGMN, candidates=THREE, **config_fields):
    library = _library()
    case = {c["case_id"]: c for c in json.loads((INPUT / "manifest.json").read_text())["cases"]}["DEV006"]
    request = RefinementInput(
        pattern_path=INPUT / case["pattern_file"],
        cif_paths=[INPUT / "candidates/DEV006" / library[c]["file"] for c in candidates],
        phase_ids=list(candidates),
        working_dir=tmp_path,
        hypothesis_id="fit",
    )
    engine = backend_module.BGMNBackend(str_cache=StrCache(tmp_path / "str_cache"))
    monkeypatch.setattr(engine, "is_available", lambda: True)
    monkeypatch.setattr(engine, "_ensure_runner", lambda: bgmn)
    return engine, request, _config(tmp_path, **config_fields)


def _run(monkeypatch, tmp_path: Path, bgmn: FakeBGMN, candidates=THREE, **config_fields):
    engine, request, config = _refine(monkeypatch, tmp_path, bgmn, candidates, **config_fields)
    return engine.refine(request, config)


def test_the_control_fit_repeats_the_final_stage_from_the_same_start_with_texture_off(monkeypatch, tmp_path: Path) -> None:
    bgmn = FakeBGMN()
    output = _run(monkeypatch, tmp_path, bgmn)
    final, control = bgmn.read[FINAL_SAV], bgmn.read[CONTROL_SAV]
    assert output.rietveld_texture_control.rwp == 4.06
    assert all("GEWICHT=SPHAR4" in text for text in final["str"])
    assert all("PARAM=GEWICHT=0_0" in text for text in control["str"])

    def settings(text: str) -> str:
        return STAMP.sub("", text).replace("PARAM=GEWICHT=0_0", "GEWICHT=SPHAR4")

    assert [settings(text) for text in control["str"]] == [settings(text) for text in final["str"]]

    def run_file(text: str) -> list[str]:
        return [line for line in text.replace("_rietveld_texture_control", "_rietveld").replace("rietveld_texture_control stage", "rietveld stage").splitlines()
                if not line.startswith("STRUC[")]

    assert run_file(control["sav"]) == run_file(final["sav"])


def test_it_changes_no_file_the_fit_wrote_and_no_result_of_the_fit(monkeypatch, tmp_path: Path) -> None:
    with_control = tmp_path / "with"
    without = tmp_path / "without"
    original = backend_module.BGMNBackend._run_texture_control
    seen: dict[str, dict[str, str]] = {}

    def hashes(work_dir: Path) -> dict[str, str]:
        return {path.name: hashlib.sha256(path.read_bytes()).hexdigest() for path in work_dir.iterdir() if path.is_file()}

    def watched(self, input, config, work_dir, *args, **kwargs):
        seen["before"] = hashes(work_dir)
        result = original(self, input, config, work_dir, *args, **kwargs)
        seen["after"] = hashes(work_dir)
        return result

    monkeypatch.setattr(backend_module.BGMNBackend, "_run_texture_control", watched)
    output = _run(monkeypatch, with_control, FakeBGMN())
    assert seen["before"].items() <= seen["after"].items()
    assert {name for name in seen["after"] if name not in seen["before"] and not name.endswith(".str")} == {
        f"DEV006_rietveld_texture_control{suffix}" for suffix in (".lst", ".dia", ".sav")
    }

    monkeypatch.setattr(backend_module.BGMNBackend, "_run_texture_control", lambda self, *a, **k: None)
    plain = _run(monkeypatch, without, FakeBGMN())
    assert output.rietveld_texture_control is not None and plain.rietveld_texture_control is None

    def comparable(stage) -> dict:
        return {key: value for key, value in asdict(stage).items() if key not in ("elapsed_seconds", "dia_data", "phases")}

    assert [comparable(stage) for stage in output.stages] == [comparable(stage) for stage in plain.stages]
    assert [s.stage.value for s in output.stages] == ["pawley", "rietveld_lattice", "rietveld_profile", "rietveld"]
    assert output.best_result is output.rietveld
    assert output.weight_fractions == plain.weight_fractions and output.final_rwp == plain.final_rwp
    assert calculate_stage_degradation_evidence(output) == calculate_stage_degradation_evidence(plain)


@pytest.mark.parametrize(
    "failure",
    [BGMNTimeoutError("t"), BGMNCrashError("c"), ValueError("unreadable output")],
    ids=["timeout", "crash", "other"],
)
def test_a_failed_control_fit_leaves_the_result_unchanged(monkeypatch, tmp_path: Path, failure: Exception) -> None:
    output = _run(monkeypatch, tmp_path, FakeBGMN(fail=failure))
    assert output.rietveld_texture_control is None
    assert output.refinement_failed is False and output.failure_reason is None
    assert output.best_result is output.rietveld and output.rietveld.rwp == 3.52


@pytest.mark.parametrize(
    ("candidates", "fields", "final_lst"),
    [
        (THREE[:1], {}, FINAL_LST),
        (THREE, {"rietveld": RietveldConfig(gewicht="0_0")}, FINAL_LST),
        (THREE, {}, FINAL_LST.replace("Rpb=14.46%", "Rpb=100.00%")),
        (THREE, {"pawley_only": True}, FINAL_LST),
    ],
    ids=["one phase", "no texture model", "final stage unconverged", "pawley only"],
)
def test_it_runs_only_after_a_converged_textured_final_stage_of_two_or_more_phases(
    monkeypatch, tmp_path: Path, candidates, fields: dict, final_lst: str
) -> None:
    bgmn = FakeBGMN(final_lst=final_lst)
    output = _run(monkeypatch, tmp_path, bgmn, candidates, **fields)
    assert CONTROL_SAV not in bgmn.read and output.rietveld_texture_control is None


def test_a_phase_override_applies_to_the_control_fit_and_cannot_turn_texture_on(monkeypatch, tmp_path: Path) -> None:
    bgmn = FakeBGMN()
    overrides = {"cod_1010093": {"rietveld": {"gewicht": "SPHAR2", "b1": "0_0^0.02"}}}
    _run(monkeypatch, tmp_path, bgmn, phase_stage_overrides=overrides)
    assert "GEWICHT=SPHAR2" in bgmn.read[FINAL_SAV]["str"][0] and "PARAM=B1=0_0^0.02" in bgmn.read[FINAL_SAV]["str"][0]
    assert "PARAM=GEWICHT=0_0" in bgmn.read[CONTROL_SAV]["str"][0] and "PARAM=B1=0_0^0.02" in bgmn.read[CONTROL_SAV]["str"][0]


def _refine_py(monkeypatch, tmp_path: Path, capsys, bgmn: FakeBGMN) -> tuple[Path, str]:
    """A real refine.py run, its backend reading a fake BGMN. Returns its run directory and stdout."""
    monkeypatch.syspath_prepend(str(PHYSICS))
    spec = importlib.util.spec_from_file_location("refine_control", PHYSICS / "refine.py")
    refine = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(refine)
    monkeypatch.setattr(backend_module.BGMNBackend, "is_available", lambda self: True)
    monkeypatch.setattr(backend_module.BGMNBackend, "_ensure_runner", lambda self: bgmn)
    monkeypatch.setattr("sys.argv", ["refine.py", "--input-dir", str(INPUT), "--output-dir", str(tmp_path), "--case", "DEV006",
                                     "--candidates", *THREE, "--run-label", "r1"])
    refine.main()
    return tmp_path / "r1", capsys.readouterr().out


@pytest.fixture
def run_dir(monkeypatch, tmp_path: Path, capsys) -> Path:
    return _refine_py(monkeypatch, tmp_path, capsys, FakeBGMN())[0]


@pytest.mark.parametrize("gewicht", ["UNDEF", "ERROR", "0.0+-0.1", "0.08+-0.1"])
def test_a_control_amount_bgmn_could_not_weigh_is_not_available_in_the_line_and_k6(
    gewicht: str, monkeypatch, tmp_path: Path, capsys
) -> None:
    third = list(re.finditer(r"(?m)^GEWICHT=\S+$", CONTROL_LST))[2]
    control_lst = CONTROL_LST[: third.start()] + f"GEWICHT={gewicht}" + CONTROL_LST[third.end() :]

    run, printed = _refine_py(monkeypatch, tmp_path, capsys, FakeBGMN(control_lst=control_lst))

    result = json.loads((run / "result.json").read_text())
    assert result["texture_dependence"] is None
    assert "Texture dependence: not available (needs" in printed and "largest amount change" not in printed
    check = k6(_recorded_fit("r1", result, json.loads((run / "request.json").read_text())), (10.0, 80.0))
    assert check["status"] == "not_computable"
    assert "Texture dependence: not available" in check["detail"] and "largest amount change" not in check["detail"]


def test_refine_py_records_the_control_fit_without_a_curve_and_its_comparison(run_dir: Path) -> None:
    result = json.loads((run_dir / "result.json").read_text())
    assert result["rietveld_texture_control"]["stage"] == "rietveld_texture_control"
    assert "curve_file" not in result["rietveld_texture_control"]
    assert not (run_dir / "rietveld_texture_control.csv").exists()
    assert [Path(path).name for path in result["curve_files"]] == ["pawley.csv", "rietveld_lattice.csv", "rietveld_profile.csv", "rietveld.csv"]
    assert result["texture_dependence"]["rwp_control"] == 4.06 and result["texture_dependence"]["rwp_final"] == 3.52
    assert result["stage_degradation"]["selected_stage"] == "rietveld"


def test_every_stage_consumer_of_a_recorded_run_reads_the_fit_alone(run_dir: Path) -> None:
    result = json.loads((run_dir / "result.json").read_text())
    request = json.loads((run_dir / "request.json").read_text())
    fit = _recorded_fit("r1", result, request)
    assert list(fit.stages) == ["pawley", "rietveld_lattice", "rietveld_profile", "rietveld"] and fit.rwp == 3.52

    assert executors._stage_lst(run_dir / "fit", "rietveld").name == "DEV006_rietveld.lst"
    record = executors.read_recorded_execution(run_dir, binary_sha256=None)
    assert [stage.stage for stage in record.result.stages] == ["pawley", "rietveld_lattice", "rietveld_profile", "rietveld"]
    native = executors.native_artifacts(run_dir, record.result)
    assert not [ref for ref, data in native.values() if b"Rwp=4.06" in data]

