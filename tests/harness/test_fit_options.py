def _sav(tmp_path: Path, config: RefinementConfig, stage: RefinementStage = RefinementStage.RIETVELD) -> str:
    tmp_path.mkdir(exist_ok=True)
    pattern = tmp_path / "scan.xy"
    pattern.write_text("10.0 5.0\n11.0 6.0\n")
    structure = tmp_path / "one.str"
    structure.write_text("PHASE=one //\nRP=4 k1=0 k2=0 B1=0 GEWICHT=0_0 //\n")
    return generate_sav(pattern, [structure], config, tmp_path / "work", stage).read_text()


DEFAULT_RIETVELD_SAV = """\
% Control file generated by AgentXRD (rietveld stage)
% Theoretical instrumental function
VERZERR=Aeris-fds-Pixcel1d-Medipix3.geq
% Wavelength
LAMBDA=CU
% Phases
STRUC[1]=one.str
% Measured data
VAL[1]=scan.xy
% Result list output
LIST=scan_rietveld.lst
% Peak list output
OUTPUT=scan_rietveld.par
% Diagram output
DIAGRAMM=scan_rietveld.dia
% Global parameters for zero point and sample displacement
EPS1=0.0
PARAM[1]=EPS2=0_-0.01^0.01
NTHREADS=8
PROTOKOLL=Y
sum=one
Qone=one/sum
GOAL[1]=Qone
"""


def test_a_default_fit_writes_the_old_control_file_with_only_the_new_eps2_bound(tmp_path: Path, refine) -> None:
    assert _sav(tmp_path, RefinementConfig(**refine.FitOptions().config_fields())) == DEFAULT_RIETVELD_SAV


def test_refined_corrections_take_sequential_param_indices_and_an_unset_eps3_is_omitted(tmp_path: Path) -> None:
    both = _sav(tmp_path / "a", RefinementConfig(eps1="0_-0.01^0.01", eps3="0_-0.01^0.01"))
    assert "PARAM[1]=EPS1=0_-0.01^0.01\nPARAM[2]=EPS2=0_-0.01^0.01\nPARAM[3]=EPS3=0_-0.01^0.01\n" in both
    eps3 = _sav(tmp_path / "b", RefinementConfig(eps3="0_-0.01^0.01"))
    assert "EPS1=0.0\nPARAM[1]=EPS2=0_-0.01^0.01\nPARAM[2]=EPS3=0_-0.01^0.01\n" in eps3
    assert "EPS3" not in _sav(tmp_path / "c", RefinementConfig())


def test_a_grain_diameter_is_written_only_when_set(tmp_path: Path) -> None:
    assert "\nd=7.5\n" in _sav(tmp_path / "a", RefinementConfig(grain_diameter_um=7.5))
    assert "\nd=" not in _sav(tmp_path / "b", RefinementConfig())


