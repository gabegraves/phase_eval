def _main(refine, monkeypatch, tmp_path: Path, *flags: str) -> Path:
    input_dir = ROOT / "harness/examples/dev006/input"
    library = json.loads((input_dir / "candidates/DEV006/manifest.json").read_text())["candidates"]

    class Backend:
        def __init__(self, str_cache) -> None:
            pass

        def refine(self, request, config):
            return RefinementOutput(hypothesis_id="fit", working_dir=request.working_dir, refinement_failed=True, failure_reason="stub")

    monkeypatch.setattr(refine, "BGMNBackend", Backend)
    monkeypatch.setattr("sys.argv", ["refine.py", "--input-dir", str(input_dir), "--output-dir", str(tmp_path), "--case", "DEV006",
                                     "--candidates", library[0]["candidate_id"], "--run-label", "r1", *flags])
    refine.main()
    return tmp_path / "r1"


def test_the_command_line_records_the_options_in_the_receipt(refine, monkeypatch, tmp_path: Path) -> None:
    run = _main(refine, monkeypatch, tmp_path, "--texture-order", "0", "--refine-zero", "--refine-transparency", "--grain-diameter-um", "5")
    config = json.loads((run / "request.json").read_text())["config"]
    assert config["rietveld"]["gewicht"] == "0_0"
